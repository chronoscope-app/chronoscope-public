#!/usr/bin/env node
// Regenerate from the Rust registry and its input/output schemas. No network.
import fs from "node:fs";
import path from "node:path";
import {spawnSync} from "node:child_process";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const binary=process.env.CHRONOSCOPE_CLI||path.join(root,"target/debug/chronoscope"+(process.platform==="win32"?".exe":""));
const result=spawnSync(binary,["schema"],{encoding:"utf8",maxBuffer:16*1024*1024});
if(result.status!==0)throw Error("Build the CLI before generating contracts: cargo build --locked -p chronoscope --bin chronoscope\n"+(result.stderr||result.error||""));
const api=JSON.parse(result.stdout);
function type(schema,rootSchema=schema,seen=new Set()){
  if(schema===true)return "unknown";if(schema===false)return "never";
  if(schema.$ref){if(seen.has(schema.$ref))return "unknown";const child=schema.$ref.split("/").slice(1).reduce((v,k)=>v?.[k.replace(/~1/g,"/").replace(/~0/g,"~")],rootSchema);return type(child||{},rootSchema,new Set([...seen,schema.$ref]));}
  if("const" in schema)return JSON.stringify(schema.const);
  if(schema.enum)return schema.enum.map(v=>JSON.stringify(v)).join(" | ");
  if(schema.anyOf||schema.oneOf)return "("+(schema.anyOf||schema.oneOf).map(s=>type(s,rootSchema,seen)).join(" | ")+")";
  if(schema.allOf)return "("+schema.allOf.map(s=>type(s,rootSchema,seen)).join(" & ")+")";
  if(Array.isArray(schema.type))return schema.type.map(t=>type({...schema,type:t},rootSchema,seen)).join(" | ");
  switch(schema.type){
    case "null":return "null";
    case "boolean":return "boolean";
    case "string":return "string";
    case "number":case "integer":return "number";
    case "array":if(schema.minItems===schema.maxItems && schema.minItems>0 && schema.minItems<=16 && !schema.prefixItems)return "["+Array.from({length:schema.minItems},()=>type(schema.items||{},rootSchema,seen)).join(", ")+"]";if(schema.prefixItems)return "["+schema.prefixItems.map(s=>type(s,rootSchema,seen)).join(", ")+"]";return "Array<"+type(schema.items||{},rootSchema,seen)+">";
    case "object":{
      const required=new Set(schema.required||[]);
      const fields=Object.entries(schema.properties||{}).map(([k,v])=>JSON.stringify(k)+(required.has(k)?"":"?")+": "+type(v,rootSchema,seen)+";");
      if(schema.additionalProperties!==false)fields.push("[key: string]: "+(typeof schema.additionalProperties==="object"?type(schema.additionalProperties,rootSchema,seen):"any")+";");
      return "{ "+fields.join(" ")+" }";
    }
    default:return "any"; // Explicitly opaque/projection-dependent JSON fields.
  }
}
let source="// Generated by scripts/generate_contracts.mjs from Rust. Do not edit.\n";
source+="export type ErrorCode = "+type(api.error_codes)+";\nexport interface EngineContracts {\n";
for(const [name,schema] of Object.entries(api.commands))source+=`  ${JSON.stringify(name)}: { args: ${type(schema.input)}; result: ${type(schema.output)} };\n`;
source+="}\nexport type EngineCommand = keyof EngineContracts;\n";
source+="export const commandNames = "+JSON.stringify(Object.keys(api.commands))+" as const;\n";
const destination=path.join(root,"frontend/src/contracts.ts");
if(process.argv.includes("--check")){if(!fs.existsSync(destination)||fs.readFileSync(destination,"utf8")!==source)throw Error("Generated engine contracts are stale. Run node scripts/generate_contracts.mjs");console.log("Generated engine contracts match Rust.");}
else{fs.writeFileSync(destination,source);console.log(destination);}
