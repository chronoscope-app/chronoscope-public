import { withLocalApp } from "./local-browser.mjs";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

await withLocalApp("import-layers", async ({ page, api, out, pass }) => {
  await page.locator("#welcome-empty").click();
  const open = async (name) => {
    const file=path.join(out,name);
    fs.writeFileSync(file,"entity,time,latitude,longitude\nA,2026-10-31T12:00:00Z,40,-73\n");
    page.once("dialog",dialog=>dialog.accept(file));
    await page.locator("#open").click();
    await page.locator("#review-import").waitFor();
  };
  const commit = async () => {
    await page.locator("#review-import").click();
    await page.waitForFunction(()=>!document.querySelector("#commit-import")?.disabled);
    await page.locator("#commit-import").click();
    await page.locator("#import-dialog").waitFor({state:"detached"});
    await page.waitForFunction(()=>!window.__chronoscope.busy);
  };
  await open("first.csv"); await commit();
  const first=(await api("snapshot")).layers[0].source;
  await open("second.csv");
  await page.locator("#import-target-layer").selectOption(first);
  assert(await page.locator("#append-import").isChecked());
  assert(await page.locator("#append-import").isDisabled());
  await commit();
  let snapshot=await api("snapshot");
  assert.equal(snapshot.count,2);assert.equal(snapshot.layers.length,1);
  const rows=await api("query",{limit:10});
  assert(rows.events.some(row=>row.attrs.chronoscope_original_source==="second.csv / CSV"));
  pass("Destination layer merges a second file into one layer and retains source provenance");
  await open("third.csv");
  await page.locator("#append-import").check();
  await commit();
  snapshot=await api("snapshot");
  assert.equal(snapshot.layers.length,2);assert.equal(snapshot.count,3);
  await page.locator(`[data-layer-source="${first}"]`).click({button:"right"});
  await page.locator("#show-only-layer").click();
  await page.waitForFunction((first)=>window.__chronoscope.snapshot.layers.every(l=>l.enabled===(l.source===first)),first);
  assert.equal((await api("snapshot")).visible,2);
  const third=snapshot.layers.find(l=>l.source!==first).source;
  await page.locator(`[data-layer-source="${third}"] [data-layer-menu]`).click();
  await page.locator("#show-only-layer").click();
  await page.waitForFunction((third)=>window.__chronoscope.snapshot.layers.every(l=>l.enabled===(l.source===third)),third);
  assert.equal((await api("snapshot")).visible,1);
  await page.screenshot({path:path.join(out,"show-only-layer.png")});
  pass("Right-click and ellipsis Show only this layer both hide other data layers and enable the chosen layer");
  const geo=path.join(out,"reference.geojson");
  fs.writeFileSync(geo,JSON.stringify({type:"FeatureCollection",features:[{type:"Feature",properties:{name:"reference"},geometry:{type:"Point",coordinates:[-73,40]}}]}));
  const loaded=await api("gis_load",{path:geo});
  await page.reload();
  await page.waitForFunction(()=>window.__chronoscope?.snapshot && !window.__chronoscope.busy);
  await page.locator(`[data-layer-source="${first}"] [data-layer-menu]`).click();
  await page.locator("#show-only-layer").click();
  await page.waitForFunction(()=>window.__chronoscope.snapshot.gis_layers.every(l=>!l.enabled));
  const gis=(await api("gis_layers")).layers[0];
  await page.locator(`[data-gis-id="${gis.id}"] [data-gis-options]`).click();
  await page.locator("#gis-layer-only").click();
  await page.waitForFunction(()=>window.__chronoscope.snapshot.layers.every(l=>!l.enabled) && window.__chronoscope.snapshot.gis_layers.every(l=>l.enabled));
  pass("Show only this layer also isolates GIS layers and hides other Event/GIS layers");
  assert(!(await api("demo_catalog")).demos.some(d=>d.id==="idf-uav"));
  await page.evaluate(async()=>{
    const c=window.__chronoscope;
    const result=await c.call("demo_open",{id:"flight-altitude"});
    await c.restoreScene(result.scene);
  });
  await page.waitForFunction(()=>window.__chronoscope.snapshot.count===11018 && !window.__chronoscope.busy);
  assert.equal((await api("snapshot")).layers.length,1);
  pass("Multi-file Philippine flight demo displays one layer");
});
